const assert = require('node:assert/strict')
const { Pool } = require('pg')
const { assertShippingPayable, applyShippingFee } = require('../src/lib/hash/shipping-fees')
if (!process.env.DATABASE_URL || !['localhost','127.0.0.1'].includes(new URL(process.env.DATABASE_URL).hostname)) throw Error('Use the local fixture database')
const pool = new Pool({ connectionString:process.env.DATABASE_URL })
;(async()=>{
 const c = await pool.connect()
 try {
  await c.query('BEGIN')
  const { rows:[order] } = await c.query('SELECT order_id,vendor_id FROM hash_order WHERE order_id NOT IN (SELECT order_id FROM hash_shipment) LIMIT 1 FOR UPDATE')
  assert(order,'A local order fixture without a shipment is required')
  await c.query("UPDATE hash_order SET delivery_kind='service' WHERE order_id=$1",[order.order_id])
  await assertShippingPayable(c,order.order_id)
  await c.query("UPDATE hash_order SET delivery_kind='product' WHERE order_id=$1",[order.order_id])
  await assert.rejects(()=>assertShippingPayable(c,order.order_id),/final Delhivery invoice/)
  await c.query("INSERT INTO hash_shipment(order_id,vendor_id,parcel,pickup,quote_paise) VALUES($1,$2,'{}','{}',10000)",[order.order_id,order.vendor_id])
  await assert.rejects(()=>assertShippingPayable(c,order.order_id),/final Delhivery invoice/)
  await c.query("UPDATE hash_shipment SET status='booked',waybill='LOCAL-QA' WHERE order_id=$1",[order.order_id])
  await assert.rejects(()=>assertShippingPayable(c,order.order_id),/final Delhivery invoice/)
  await c.query("UPDATE hash_shipment SET fee_final=true,fee_paise=10000,invoice_reference='LOCAL-QA' WHERE order_id=$1",[order.order_id])
  await assertShippingPayable(c,order.order_id)
  await c.query("UPDATE hash_order SET commercial_snapshot=jsonb_build_object('gateway_payer','vendor'),gateway_fee_paise=NULL WHERE order_id=$1",[order.order_id])
  await assert.rejects(()=>assertShippingPayable(c,order.order_id),/Verified Razorpay/)
  await c.query("UPDATE hash_order SET gateway_fee_paise=500,net_paise=20000,shipping_fee_paise=10000,settlement_plan=jsonb_build_object('capture_bps',5000) WHERE order_id=$1",[order.order_id])
  await assertShippingPayable(c,order.order_id)
  for (const milestone of ['payment','completion']) {
   await c.query("INSERT INTO hash_settlement(id,order_id,vendor_id,milestone,amount_paise,due_at) VALUES($1,$2,$3,$4,0,now()) ON CONFLICT(order_id,milestone) DO UPDATE SET status='scheduled',amount_paise=0",['local-fee-check-'+milestone,order.order_id,order.vendor_id,milestone])
  }
  await applyShippingFee(c,order.order_id)
  const {rows:amounts}=await c.query("SELECT amount_paise FROM hash_settlement WHERE order_id=$1 ORDER BY milestone",[order.order_id])
  assert.deepEqual(amounts.map(s=>Number(s.amount_paise)),[4750,4750])
  await applyShippingFee(c,order.order_id)
  const {rows:[sum]}=await c.query("SELECT sum(amount_paise) AS amount FROM hash_settlement WHERE order_id=$1",[order.order_id])
  assert.equal(Number(sum.amount),9500)
  console.log('PASS vendor-funded gateway payouts require verified charges')
  console.log('PASS shared payout guard blocks physical orders before booking, quoting and invoice reconciliation; services and reconciled orders pass')
 } finally { await c.query('ROLLBACK'); c.release() }
})().catch(error=>{console.error(error.message);process.exitCode=1}).finally(()=>pool.end())
